@Suite("paste history: the picker")
@MainActor
struct PasteHistoryPickerTests {
    private func entry(
        _ id: Int64, _ content: String, kind: ClipKind = .paste, source: ClipSource = .pty,
        redacted: Bool = false, at: Int64 = 0
    ) -> ClipEntry {
        ClipEntry(
            id: id, kind: kind, source: source, content: content, redacted: redacted,
            lineCount: UInt32(content.split(separator: "\n").count), byteCount: UInt64(content.utf8.count), at: at)
    }

    @Test("nothing typed is everything, newest first as given; typing keeps the order and filters by substring")
    func ranking() {
        let all = [
            entry(3, "git push origin main"), entry(2, "/Users/you/code/max-pane/README.md"),
            entry(1, "git commit --amend\nGit is fine"),
        ]
        #expect(PasteHistory.filter(all, query: "").map(\.id) == [3, 2, 1])
        #expect(PasteHistory.filter(all, query: "  ").map(\.id) == [3, 2, 1])
        #expect(PasteHistory.filter(all, query: "GIT").map(\.id) == [3, 1], "case is ignored, newest stays first")
        #expect(PasteHistory.filter(all, query: "git amend").map(\.id) == [1], "every word must be there")
        #expect(PasteHistory.filter(all, query: "readme").map(\.id) == [2])
        #expect(PasteHistory.filter(all, query: "gti").isEmpty, "substring, not fuzzy")
    }

    @Test("a row is one line: the first with anything on it, or the one that matched")
    func headline() {
        let e = entry(1, "\n  cd /tmp\n\tmake all\n")
        #expect(PasteHistory.headline(e) == "cd /tmp")
        #expect(PasteHistory.headline(e, query: "make") == "make all")
        #expect(PasteHistory.headline(e, query: "nothing") == "cd /tmp")
        #expect(PasteHistory.headline(entry(2, "a\tb\u{1b}[0m")) == "a␉b␛[0m")
        #expect(PasteHistory.matches(in: "make all", query: "MA l") == [0, 1, 6, 7])
    }

    @Test("the detail line has which way, the line count, the size and the age")
    func detail() {
        let now = Date(timeIntervalSince1970: 10_000)
        let pasted = entry(1, "a\nb\nc", at: Int64((10_000 - 300) * 1000))
        #expect(PasteHistory.detail(pasted, now: now) == "pasted · 3 lines · 5 bytes · 5m ago")
        let copied = entry(2, "x", kind: .copy, at: Int64(10_000 * 1000))
        #expect(PasteHistory.detail(copied, now: now) == "copied · 1 line · 1 byte · now")
        let secret = entry(3, "expo•••", redacted: true, at: Int64(10_000 * 1000))
        #expect(PasteHistory.detail(secret, now: now).hasPrefix("looked like a secret, not kept · pasted"))
    }

    @Test("every row says which kind of pane it came from")
    func chip() {
        #expect(PasteHistory.chipText(entry(1, "ls")) == "PTY")
        #expect(PasteHistory.chipText(entry(2, "a token", kind: .copy, source: .web)) == "WEB")
        // The chip is on the row itself, not only in the model.
        let row = PasteHistoryRow(entry: entry(3, "a token", kind: .copy, source: .web), query: "")
        let words = row.subviews.flatMap { $0.subviews }.compactMap { ($0 as? NSTextField)?.stringValue }
        #expect(words.contains("WEB"))
    }

    @MainActor
    private final class Rig {
        let dir: URL
        let store: StripStore
        let paneId: String
        var config = Config()
        let pasteboard = NSPasteboard(name: .init("maxpane.tests.paste-history.picker.\(UUID().uuidString)"))
        var delivered: [ClipEntry?] = []

        init() throws {
            dir = FileManager.default.temporaryDirectory
                .appendingPathComponent("maxpane-paste-history-picker-\(UUID().uuidString)")
            try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
            store = try StripStore(ledgerPath: dir.appendingPathComponent("ledger.db").path)
            try store.newTerminalLane(relaySessionId: "picker", near: nil)
            paneId = store.state.lanes[0].panes[0].id
            pasteboard.clearContents()
        }

        func keep(_ text: String, _ kind: ClipKind = .paste, _ source: ClipSource = .pty) {
            store.recordClip(paneId: paneId, kind: kind, source: source, text: text, config: config)
        }

        func picker(canPaste: Bool = true) -> PasteHistoryController {
            let picker = PasteHistoryController(
                store: store, config: { [unowned self] in self.config }, canPaste: canPaste, pasteboard: pasteboard
            ) { [unowned self] in self.delivered.append($0) }
            picker.reload()
            return picker
        }

        func close() {
            pasteboard.releaseGlobally()
            try? FileManager.default.removeItem(at: dir)
        }
    }

    @Test("the list is the ledger's, newest first, and typing filters it")
    func lists() throws {
        let rig = try Rig()
        defer { rig.close() }
        rig.keep("/tmp/a path")
        rig.keep("git status", .copy)
        let picker = rig.picker()
        #expect(picker.visible.map(\.content) == ["git status", "/tmp/a path"])
        #expect(picker.numberOfRows() == 2)
        #expect(picker.view(forRow: 0) is PasteHistoryRow)
        picker.setQuery("path")
        picker.reload()
        #expect(picker.visible.map(\.content) == ["/tmp/a path"])
        #expect(picker.footerLeft.stringValue == "1 OF 2")
    }

    @Test("↩ hands the entry to be pasted; a redacted row and a picker with no terminal hand over nothing")
    func pastePath() throws {
        let rig = try Rig()
        defer { rig.close() }
        rig.keep("export KEY=sk-ant-api03-abcdefghijklmnopqrstuvwx")
        rig.keep("ls -la")
        let picker = rig.picker()
        picker.deliver(selected: 0)
        #expect(rig.delivered.last??.content == "ls -la")
        picker.deliver(selected: 1)
        #expect(rig.delivered.count == 2 && rig.delivered[1] == nil)
        #expect(picker.pasteRefusal(picker.visible[1]) != nil)
        picker.deliver(selected: -1)
        #expect(rig.delivered.count == 3 && rig.delivered[2] == nil)

        let noTerminal = rig.picker(canPaste: false)
        noTerminal.deliver(selected: 0)
        #expect(rig.delivered.count == 4 && rig.delivered[3] == nil)
        #expect(noTerminal.footerRight.stringValue.hasPrefix("⌘C"))
    }

    @Test("⌘C puts the row back on the clipboard it was given, and a redacted row has nothing to copy")
    func copies() throws {
        let rig = try Rig()
        defer { rig.close() }
        rig.keep("ghp_abcdefghijklmnopqrstuvwxyz0123456789")
        rig.keep("one\ntwo\n")
        let picker = rig.picker()
        #expect(picker.copy(row: 0))
        #expect(rig.pasteboard.string(forType: .string) == "one\ntwo\n")
        #expect(!picker.copy(row: 1))
        #expect(rig.pasteboard.string(forType: .string) == "one\ntwo\n")
        #expect(!picker.copy(row: 7))
    }

    @Test("deleting a row removes it from the ledger and from the list")
    func deletes() throws {
        let rig = try Rig()
        defer { rig.close() }
        for text in ["a", "b", "c"] { rig.keep(text) }
        let picker = rig.picker()
