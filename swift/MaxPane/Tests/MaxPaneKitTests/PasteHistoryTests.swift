/// Paste history (ADR-0031): what is kept of each kind of paste and copy, what
/// never is, and the picker over it. Every pasteboard here is a private named
/// one; `NSPasteboard.general` is never read or written.

@Suite("paste history: a pasteboard marked secret says so as it is read")
@MainActor
struct PasteHistoryMarkerTests {
    private func board() -> NSPasteboard {
        let board = NSPasteboard(name: .init("maxpane.tests.paste-history.marker.\(UUID().uuidString)"))
        board.clearContents()
        return board
    }

    @Test("each of the three nspasteboard.org types", arguments: [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
    ])
    func marked(type: String) {
        let board = board()
        defer { board.releaseGlobally() }
        board.declareTypes([.string, .init(type)], owner: nil)
        board.setString("hunter2", forType: .string)
        board.setString("", forType: .init(type))
        let read = TerminalPaste.clipboard(board)
        #expect(read.text == "hunter2", "it still pastes")
        #expect(read.doNotRecord)
    }

    @Test("an ordinary copy is not marked, and neither is an empty pasteboard")
    func unmarked() {
        let board = board()
        defer { board.releaseGlobally() }
        #expect(!TerminalPaste.clipboard(board).doNotRecord)
        board.setString("ls -la", forType: .string)
        #expect(!TerminalPaste.clipboard(board).doNotRecord)
    }

    @Test("a marked pasteboard of files is marked too")
    func markedFiles() {
        let board = board()
        defer { board.releaseGlobally() }
        board.writeObjects([URL(fileURLWithPath: "/tmp/secret.key") as NSURL])
        board.addTypes([.init("org.nspasteboard.ConcealedType")], owner: nil)
        board.setString("", forType: .init("org.nspasteboard.ConcealedType"))
        let read = TerminalPaste.clipboard(board)
        #expect(read.text == "/tmp/secret.key")
        #expect(read.doNotRecord)
    }
}

@Suite("paste history: what the pane's one door records", .serialized)
@MainActor
struct PasteHistoryDoorTests {
    @MainActor
    final class Wire: RelayAttachment {
        let sessionId = "paste-history-test"
        var onData: ((ArraySlice<UInt8>) -> Void)?
        var onHostResize: ((Int, Int) -> Void)?
        var onTitle: ((String) -> Void)?
        var onExit: ((Int32) -> Void)?
        var onConnectionChange: ((Bool) -> Void)?
        var onRefused: ((String) -> Void)?
        var onReplaceScreen: (() -> Void)?
        var sent: [UInt8] = []
        func connect() {}
        func disconnect() {}
        func send(_ bytes: ArraySlice<UInt8>) { sent.append(contentsOf: bytes) }
        func send(_ bytes: ArraySlice<UInt8>, pace: PacedInput.Pace, report: @escaping (PacedInput.SlowEvent) -> Void) {
            sent.append(contentsOf: bytes)
            report(.finished(bytes.count))
        }
        func cancelSlowSend() {}
        func claimSize(cols: Int, rows: Int) {}
        var text: String { String(decoding: sent, as: UTF8.self) }
    }

    @MainActor
    final class Rig {
        let dir: URL
        let store: StripStore
        let window: NSWindow
        let pane: TerminalPaneController
        let wire = Wire()
        let pasteboard = NSPasteboard(name: .init("maxpane.tests.paste-history.\(UUID().uuidString)"))
        var config: Config

        /// `privateLane`: the terminal is a second pane of a private web lane.
        init(config: Config = Config(), privateLane: Bool = false) throws {
            self.config = config
            dir = FileManager.default.temporaryDirectory
                .appendingPathComponent("maxpane-paste-history-\(UUID().uuidString)")
            try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
            store = try StripStore(ledgerPath: dir.appendingPathComponent("ledger.db").path)
            let terminal: Pane
            if privateLane {
                try store.newWebLane(url: "https://mail.example/", near: nil, private: true)
                let lane = try #require(store.state.lanes.first)
                try store.addPane(to: lane.id, kind: .pty, relaySessionId: "paste-history", url: nil)
                terminal = try #require(store.state.lanes[0].panes.first { $0.kind == .pty })
            } else {
                try store.newTerminalLane(relaySessionId: "paste-history", near: nil)
                terminal = store.state.lanes[0].panes[0]
            }
            window = NSWindow(
                contentRect: NSRect(x: -8000, y: 200, width: 700, height: 600),
                styleMask: [.borderless], backing: .buffered, defer: false)
            window.isReleasedWhenClosed = false
            pane = TerminalPaneController(
                pane: terminal, store: store, config: config,
                controller: TerminalControllerPool.makeController(for: config))
            pane.pasteboard = pasteboard
            pane.liveConfig = { [unowned self] in self.config }
            pane.attach(wire)
            pane.view.frame = NSRect(x: 0, y: 0, width: 656, height: 600)
            window.contentView?.addSubview(pane.view)
            pasteboard.clearContents()
        }

        func copy(_ text: String, marker: String? = nil) {
            pasteboard.clearContents()
            pasteboard.setString(text, forType: .string)
            if let marker {
                pasteboard.addTypes([.init(marker)], owner: nil)
                pasteboard.setString("", forType: .init(marker))
            }
        }

        func settle() async throws { try await Task.sleep(nanoseconds: 120_000_000) }

        var history: [ClipEntry] { store.clipHistory(config) }
        var kept: [String] { history.map(\.content) }

        func close() {
            pane.tearDown()
            pasteboard.releaseGlobally()
            window.close()
            try? FileManager.default.removeItem(at: dir)
        }
    }

