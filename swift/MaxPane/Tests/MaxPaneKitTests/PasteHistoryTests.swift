        #expect(rig.store.clipHistory(rig.config).map(\.content) == ["c", "a"])
        let prompt = PasteHistory.deletePrompt(picker.visible[0])
        #expect(prompt.title == "Delete this from paste history?")
        #expect(prompt.detail == "c")
    }

    @Test("with the setting off the list is empty and says why")
